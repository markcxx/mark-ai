import { execFileSync } from "node:child_process";
import { build } from "esbuild";
import { mkdir, writeFile, copyFile, readFile } from "node:fs/promises";
import {
  bundledLanguages,
  bundledLanguagesInfo,
  bundledThemes,
  codeToTokens,
} from "shiki/bundle/full";

const shared = await build({
  stdin: {
    contents:
      'export * from "./lib/code/themes"; export { CODE_THEMES } from "./lib/visualization/theme-catalog";',
    resolveDir: process.cwd(),
    loader: "ts",
  },
  bundle: true,
  write: false,
  format: "esm",
  platform: "node",
});
const { LEGACY_CODE_THEMES, CODE_THEMES } = await import(
  `data:text/javascript;base64,${Buffer.from(shared.outputFiles[0].text).toString("base64")}`
);
if (!CODE_THEMES.length || !LEGACY_CODE_THEMES.one) throw new Error("共享代码主题配置为空");
const root = "mobile/assets/web/shiki";
await mkdir(`${root}/languages`, { recursive: true });
await mkdir(`${root}/themes`, { recursive: true });
const languages = {},
  grammarFiles = new Set(),
  themeColors = {};
for (const info of bundledLanguagesInfo) {
  const { default: grammars } = await bundledLanguages[info.id]();
  const names = grammars.map((grammar) => grammar.name);
  for (const name of [info.id, ...(info.aliases || [])]) languages[name] = names;
  for (const grammar of grammars) {
    if (grammarFiles.has(grammar.name)) continue;
    grammarFiles.add(grammar.name);
    await writeFile(`${root}/languages/${grammar.name}.json`, JSON.stringify(grammar));
  }
}
for (const { id } of CODE_THEMES) {
  if (!bundledThemes[id]) throw new Error(`Shiki 主题不存在: ${id}`);
  const { default: theme } = await bundledThemes[id]();
  await writeFile(`${root}/themes/${id}.json`, JSON.stringify(theme));
  const colors = await codeToTokens("", { lang: "text", theme: id });
  themeColors[id] = { fg: colors.fg, bg: colors.bg };
}
for (const pair of Object.values(LEGACY_CODE_THEMES)) {
  for (const id of pair) if (!themeColors[id]) throw new Error(`旧主题映射无对应资源: ${id}`);
}
const dart = (value) => JSON.stringify(value, null, 2).replace(/\$/g, "\\$");
await writeFile(
  "mobile/lib/shared/models/code_themes.dart",
  `// Generated by mobile/tool/export-code-highlighter.mjs from shared Shiki data.\nconst codeThemeOptions = ${dart(Object.fromEntries([...Object.keys(LEGACY_CODE_THEMES).map((id) => [id, id]), ...CODE_THEMES.map((t) => [t.id, t.label])]))};\nconst legacyCodeThemes = ${dart(LEGACY_CODE_THEMES)};\nconst codeThemeColors = ${dart(themeColors)};\nconst codeLanguages = ${dart(languages)};\n\nString resolveCodeTheme(String theme, bool dark) => legacyCodeThemes[theme]?[dark ? 1 : 0] ?? (codeThemeColors.containsKey(theme) ? theme : dark ? 'one-dark-pro' : 'one-light');\n`,
);
await build({
  entryPoints: ["mobile/tool/code-highlighter-runtime.ts"],
  bundle: true,
  outfile: "mobile/assets/web/code-highlighter.js",
  format: "iife",
  platform: "browser",
  target: "es2020",
  supported: { "template-literal": false },
  minify: true,
});
await copyFile("node_modules/shiki/LICENSE", `${root}/LICENSE`);
await copyFile("node_modules/@shikijs/vscode-textmate/LICENSE.md", `${root}/TEXTMATE-LICENSE`);
await copyFile(
  "node_modules/@shikijs/engine-oniguruma/LICENSE",
  `${root}/ONIGURUMA-ENGINE-LICENSE`,
);
await copyFile("node_modules/@shikijs/langs/LICENSE", `${root}/LANGUAGES-LICENSE`);
await copyFile("node_modules/@shikijs/themes/LICENSE", `${root}/THEMES-LICENSE`);
execFileSync("dart", ["format", "mobile/lib/shared/models/code_themes.dart"], { stdio: "pipe" });
const packageInfo = JSON.parse(await readFile("node_modules/shiki/package.json", "utf8"));
await writeFile(`${root}/version.json`, JSON.stringify({ shiki: packageInfo.version }));
console.log(
  `Generated Shiki ${packageInfo.version}: ${grammarFiles.size} grammars, ${Object.keys(themeColors).length} themes`,
);
